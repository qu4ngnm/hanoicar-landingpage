// ===== i18n Engine =====
let currentLang = localStorage.getItem('lang') || 'vi';

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;

  // Update text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[key] && translations[key][lang]) {
      el.innerHTML = translations[key][lang];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (translations[key] && translations[key][lang]) {
      el.placeholder = translations[key][lang];
    }
  });

  // Update meta tags
  document.title = translations.meta_title[lang];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', translations.meta_desc[lang]);

  // Update toggle button
  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.querySelector('.lang-vi').classList.toggle('active', lang === 'vi');
    toggle.querySelector('.lang-en').classList.toggle('active', lang === 'en');
  }
}

function toggleLanguage() {
  applyLanguage(currentLang === 'vi' ? 'en' : 'vi');
}

// Apply on load
document.addEventListener('DOMContentLoaded', () => applyLanguage(currentLang));
